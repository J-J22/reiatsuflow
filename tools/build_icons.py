"""Build ui/fonts/icons.ttf: just the Material Symbols Rounded icons the UI uses, as a small static
font (outlined, weight 400), plus ui/IconCodes.js mapping icon name -> codepoint.

Dev-only (the app doesn't need fontTools). Run after using a new icon name in the QML:
    pip install fonttools && python3 tools/build_icons.py [path/to/MaterialSymbolsRounded[...].ttf]
"""
import glob
import os
import re
import sys

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = sys.argv[1] if len(sys.argv) > 1 else \
    "/usr/share/fonts/ttf-material-symbols-variable/MaterialSymbolsRounded[FILL,GRAD,opsz,wght].ttf"

font = TTFont(SRC)
glyphs = set(font.getGlyphOrder())
rev = {}
for cp, g in font.getBestCmap().items():
    if cp >= 0xE000:  # private-use codepoint of each icon
        rev.setdefault(g, cp)

# every quoted lowercase word in the UI and the templates that is an icon name
text = ""
for path in glob.glob(os.path.join(ROOT, "ui", "*.qml")) + [os.path.join(ROOT, "rf", "templates.py")]:
    with open(path, encoding="utf-8") as f:
        text += f.read()
names = sorted({w for w in re.findall(r'"([a-z][a-z0-9_]+)"', text) if w in glyphs and w in rev})
print(f"{len(names)} icons:", " ".join(names))

inst = instancer.instantiateVariableFont(font, {"FILL": 0, "GRAD": 0, "opsz": 24, "wght": 400})
opts = subset.Options()
opts.layout_features = []
opts.name_IDs = ["*"]
opts.notdef_outline = True
sub = subset.Subsetter(opts)
sub.populate(unicodes=[rev[n] for n in names])
sub.subset(inst)
inst.save(os.path.join(ROOT, "ui", "fonts", "icons.ttf"))

with open(os.path.join(ROOT, "ui", "IconCodes.js"), "w") as f:
    f.write("// Generated by tools/build_icons.py: Material Symbols icon name -> codepoint.\n.pragma library\n")
    f.write("var codes = {\n" + ",\n".join(f'    "{n}": 0x{rev[n]:x}' for n in names) + "\n}\n")
print("wrote ui/fonts/icons.ttf", os.path.getsize(os.path.join(ROOT, "ui", "fonts", "icons.ttf")), "bytes")
